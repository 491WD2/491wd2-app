function singularizeMostUsedToken(token: string): string {
  if (token.endsWith("ies") && token.length > 4) {
    return `${token.slice(0, -3)}y`;
  }
  if (token.endsWith("ses") && token.length > 4) {
    return token.slice(0, -2);
  }
  if (token.endsWith("es") && token.length > 3) {
    return token.slice(0, -2);
  }
  if (token.endsWith("s") && token.length > 2) {
    return token.slice(0, -1);
  }
  return token;
}

function normalizeMostUsedQuery(value: string): string {
  return normalizeGroceryProductName(value)
    .split(" ")
    .filter(Boolean)
    .map((part) => singularizeMostUsedToken(part))
    .join(" ");
}

function productPrimaryName(value: string): string {
  const normalized = normalizeGroceryProductName(value);
  const primary = normalized.split(",")[0]?.trim() ?? normalized;
  return normalizeMostUsedQuery(primary);
}

function scoreMostUsedProductMatch(query: string, product: HouseholdProduct): number {
  const normalizedQuery = normalizeMostUsedQuery(query);
  const fullName = normalizeMostUsedQuery(product.productName);
  const primary = productPrimaryName(product.productName);

  if (fullName === normalizedQuery || primary === normalizedQuery) {
    return 1000;
  }

  if (fullName.startsWith(`${normalizedQuery} `) || primary.startsWith(`${normalizedQuery} `)) {
    return 200;
  }

  if (fullName.includes(normalizedQuery) || primary.includes(normalizedQuery)) {
    return 100;
  }

  return 0;
}

export function getMostUsedFallbackCategory(label: string): string {
  return (
    MOST_USED_FALLBACK_CATEGORIES[label as keyof typeof MOST_USED_FALLBACK_CATEGORIES] ?? "Produce"
  );
}

export function findBestHouseholdProductMatch(
  query: string,
  products: readonly HouseholdProduct[],
): HouseholdProduct | undefined {
  let best: HouseholdProduct | undefined;
  let bestScore = 0;

  for (const product of products) {
    const score = scoreMostUsedProductMatch(query, product);
    if (score > bestScore) {
      best = product;
      bestScore = score;
    } else if (score > 0 && score === bestScore && best) {
      const productLength = normalizeGroceryProductName(product.productName).length;
      const bestLength = normalizeGroceryProductName(best.productName).length;
      if (productLength < bestLength) {
        best = product;
      }
    }
  }

  return bestScore > 0 ? best : undefined;
}

export function normalizeGroceryCategory(value: string): string {
  return value.trim().toLowerCase();
}

export function normalizeGroceryBarcode(value: string | null | undefined): string | null {
  const trimmed = value?.trim();
  if (!trimmed) {
    return null;
  }
  return trimmed.replace(/[\s-]/g, "");
}

export function findGroceryProductDuplicate(
  catalog: readonly HouseholdProduct[],
  detail: Pick<GroceryProductDetail, "id" | "productName" | "category" | "barcode">,
): GroceryProductDuplicateMatch | null {
  const barcode = normalizeGroceryBarcode(detail.barcode);
  const name = normalizeGroceryProductName(detail.productName);
  const category = normalizeGroceryCategory(detail.category);

  if (barcode) {
    const barcodeMatch = catalog.find(
      (product) => normalizeGroceryBarcode(product.barcode) === barcode && product.id !== detail.id,
    );
    if (barcodeMatch) {
      return {
        reason: "barcode",
        existingProductId: barcodeMatch.id,
        existingProductName: barcodeMatch.productName,
        existingCategory: barcodeMatch.category,
        existingBarcode: barcodeMatch.barcode,
      };
    }
  }

  if (!name) {
    return null;
  }

  const nameMatch = catalog.find(
    (product) =>
      product.id !== detail.id &&
      normalizeGroceryProductName(product.productName) === name &&
      normalizeGroceryCategory(product.category) === category,
  );

  if (!nameMatch) {
    return null;
  }

  return {
    reason: "name_category",
    existingProductId: nameMatch.id,
    existingProductName: nameMatch.productName,
    existingCategory: nameMatch.category,
    existingBarcode: nameMatch.barcode,
  };
}

