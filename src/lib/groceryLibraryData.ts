export function upsertLibraryOverride(product: HouseholdProduct) {
  const index = libraryOverrides.findIndex((entry) => entry.id === product.id);
  if (index >= 0) {
    libraryOverrides = libraryOverrides.map((entry, entryIndex) =>
      entryIndex === index ? product : entry,
    );
  } else {
    libraryOverrides = [...libraryOverrides, product];
  }
  emitLibraryOverrides();
}

export function removeLibraryOverride(productId: string) {
  const next = libraryOverrides.filter((entry) => entry.id !== productId);
  if (next.length === libraryOverrides.length) {
    return;
  }
  libraryOverrides = next;
  emitLibraryOverrides();
}

export function recordMergedProduct(duplicateId: string, canonicalId: string) {
  mergedProductTargets = { ...mergedProductTargets, [duplicateId]: canonicalId };
  emitMergedProductTargets();
}

export function dismissDuplicatePair(productIdA: string, productIdB: string) {
  const key = duplicatePairKey(productIdA, productIdB);
  if (duplicateDismissals.includes(key)) {
    return;
  }
  duplicateDismissals = [...duplicateDismissals, key];
  emitDuplicateDismissals();
}

function duplicatePairKey(productIdA: string, productIdB: string) {
  return [productIdA, productIdB].sort().join("|");
}

function isDuplicateDismissed(productIdA: string, productIdB: string, dismissals: readonly string[]) {
  return dismissals.includes(duplicatePairKey(productIdA, productIdB));
}

export function mergeHouseholdProductLibrary(
  seedProducts: readonly HouseholdProduct[],
  overrides: readonly HouseholdProduct[],
  extras: readonly HouseholdProduct[],
  mergedTargets: Readonly<Record<string, string>>,
): HouseholdProduct[] {
  const overrideMap = new Map(overrides.map((product) => [product.id, product]));
  const byId = new Map<string, HouseholdProduct>();

  for (const product of seedProducts) {
    const override = overrideMap.get(product.id);
    byId.set(product.id, override ? { ...product, ...override } : { ...product });
  }

  for (const override of overrides) {
    if (!byId.has(override.id)) {
      byId.set(override.id, { ...override });
    }
  }

  for (const extra of extras) {
    const existing = byId.get(extra.id);
    const override = overrideMap.get(extra.id);
    byId.set(extra.id, existing ? { ...existing, ...extra, ...(override ?? {}) } : { ...extra });
  }

  return [...byId.values()].filter((product) => mergedTargets[product.id] == null);
}

export function buildProductLibraryStats(catalog: readonly HouseholdProduct[]): ProductLibraryStats {
  const duplicateGroups = findProductLibraryDuplicateGroups(catalog, []);
  const duplicateProductIds = new Set(
    duplicateGroups.flatMap((group) => group.products.map((product) => product.id)),
  );

  return {
    totalProducts: catalog.length,
    missingImages: catalog.filter((product) => !product.imageUrl?.trim()).length,
    missingBarcodes: catalog.filter((product) => !normalizeGroceryBarcode(product.barcode)).length,
    possibleDuplicates: duplicateProductIds.size,
  };
}

export function findProductLibraryDuplicateGroups(
  catalog: readonly HouseholdProduct[],
  dismissals: readonly string[],
): ProductLibraryDuplicateGroup[] {
  const groups = new Map<string, ProductLibraryDuplicateGroup>();
  const assigned = new Set<string>();

  for (let index = 0; index < catalog.length; index += 1) {
    const product = catalog[index];
    if (!product || assigned.has(product.id)) {
      continue;
    }

    const partners = catalog.filter((candidate) => {
      if (candidate.id === product.id || assigned.has(candidate.id)) {
        return false;
      }
      if (isDuplicateDismissed(product.id, candidate.id, dismissals)) {
        return false;
      }

      const barcodeA = normalizeGroceryBarcode(product.barcode);
      const barcodeB = normalizeGroceryBarcode(candidate.barcode);
      if (barcodeA && barcodeB && barcodeA === barcodeB) {
        return true;
      }

      return (
        normalizeGroceryProductName(product.productName) ===
          normalizeGroceryProductName(candidate.productName) &&
        normalizeGroceryCategory(product.category) === normalizeGroceryCategory(candidate.category)
      );
    });

    if (partners.length === 0) {
      continue;
    }

    const members = [product, ...partners];
    const reason =
      members.some((member) => normalizeGroceryBarcode(member.barcode)) &&
      members.every(
        (member) =>
          normalizeGroceryBarcode(member.barcode) === normalizeGroceryBarcode(members[0]?.barcode),
      )
        ? "barcode"
        : "name_category";
    const groupId = members
      .map((member) => member.id)
      .sort()
      .join("|");

    groups.set(groupId, {
      id: groupId,
      reason,
      products: members,
    });
    for (const member of members) {
      assigned.add(member.id);
    }
  }

  return [...groups.values()];
}

export function productHasLibraryDuplicate(
  product: HouseholdProduct,
  catalog: readonly HouseholdProduct[],
  dismissals: readonly string[],
) {
  return catalog.some((candidate) => {
    if (candidate.id === product.id) {
      return false;
    }
    if (isDuplicateDismissed(product.id, candidate.id, dismissals)) {
      return false;
    }

    const barcodeA = normalizeGroceryBarcode(product.barcode);
    const barcodeB = normalizeGroceryBarcode(candidate.barcode);
    if (barcodeA && barcodeB && barcodeA === barcodeB) {
      return true;
    }

    return (
      normalizeGroceryProductName(product.productName) ===
        normalizeGroceryProductName(candidate.productName) &&
      normalizeGroceryCategory(product.category) === normalizeGroceryCategory(candidate.category)
    );
  });
}

export function productMatchesLibraryStatusFilter(
  product: HouseholdProduct,
  filter: ProductLibraryStatusFilter,
  options: {
    duplicateCatalog: readonly HouseholdProduct[];
    duplicateDismissals: readonly string[];
    isOnShoppingList: boolean;
    isInPantry: boolean;
  },
) {
  if (filter === "all") {
    return true;
  }
  if (filter === "missing-image") {
    return !product.imageUrl?.trim();
  }
  if (filter === "missing-barcode") {
    return !normalizeGroceryBarcode(product.barcode);
  }
  if (filter === "missing-store") {
    return !product.store.trim();
  }
  if (filter === "duplicates") {
    return productHasLibraryDuplicate(product, options.duplicateCatalog, options.duplicateDismissals);
  }
  if (filter === "on-shopping") {
    return options.isOnShoppingList;
  }
  return options.isInPantry;
}

export function productNeedsLibraryReview(
  product: HouseholdProduct,
  options: {
    duplicateCatalog: readonly HouseholdProduct[];
    duplicateDismissals: readonly string[];
  },
): boolean {
  if (
    !product.imageUrl?.trim() ||
    !normalizeGroceryBarcode(product.barcode) ||
    !product.store.trim() ||
    !product.category.trim()
  ) {
    return true;
  }
  return productHasLibraryDuplicate(product, options.duplicateCatalog, options.duplicateDismissals);
}

